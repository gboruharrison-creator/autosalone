export const getBrands = (): string[] =>
  [...new Set(cars.map(c => c.brand))].sort();

export const getFeatured = (): Car[] =>
  cars.filter(c => c.featured && c.status === 'available');

export const getByCondition = (condition: 'new' | 'used'): Car[] =>
  cars.filter(c => c.condition === condition);

export const getById = (id: string): Car | undefined =>
  cars.find(c => c.id === id);

export const getSimilar = (car: Car, limit = 3): Car[] =>
  cars
    .filter(c => c.id !== car.id && c.condition === car.condition && c.status === 'available')
    .slice(0, limit);